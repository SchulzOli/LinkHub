import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { isAbsolute, join, relative, sep } from 'node:path'

import type { Plugin } from 'vite'

/**
 * Writes `sw.js` into the web app (PWA) build: it keeps the whole app
 * available offline, so Linkhaven opens without a network like the
 * extension does. It only ever answers requests for the app's own files;
 * everything else (sites, icons, sync) goes to the network untouched.
 *
 * A new version installs in the background and takes over the next time
 * Linkhaven is opened, so an open window never mixes old and new files.
 */

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)

    return statSync(path).isDirectory() ? listFiles(path) : [path]
  })
}

function createServiceWorker(files: string[], version: string) {
  return `// Generated by scripts/pwaServiceWorker.ts. Do not edit.
const CACHE = 'linkhaven-${version}'
const FILES = ${JSON.stringify(['./', ...files])}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('linkhaven-') && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  const url = new URL(request.url)

  if (request.method !== 'GET' || url.origin !== self.location.origin) {
    return
  }

  if (request.mode === 'navigate') {
    // The app shell: fresh when online, cached when offline.
    event.respondWith(
      fetch(request).catch(() =>
        caches.match('./', { cacheName: CACHE }).then(
          (cached) => cached || Response.error(),
        ),
      ),
    )
    return
  }

  event.respondWith(
    caches
      .match(request, { cacheName: CACHE, ignoreSearch: true })
      .then((cached) => cached || fetch(request)),
  )
})
`
}

export function pwaServiceWorker(): Plugin {
  let outDir = ''

  return {
    name: 'linkhaven-pwa-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = isAbsolute(config.build.outDir)
        ? config.build.outDir
        : join(config.root, config.build.outDir)
    },
    closeBundle() {
      const files = listFiles(outDir)
        .map((path) => relative(outDir, path).split(sep).join('/'))
        // The privacy page and the bundle report aren't needed offline.
        .filter(
          (path) =>
            path !== 'sw.js' &&
            path !== 'index.html' &&
            !path.endsWith('.map') &&
            !path.startsWith('privacy/') &&
            !path.endsWith('bundle-analysis.html'),
        )
        .sort()
      const hash = createHash('sha256')

      for (const path of ['index.html', ...files]) {
        hash.update(path).update(readFileSync(join(outDir, path)))
      }

      // closeBundle runs once every file is written.
      writeFileSync(
        join(outDir, 'sw.js'),
        createServiceWorker(files, hash.digest('hex').slice(0, 12)),
      )
    },
  }
}
