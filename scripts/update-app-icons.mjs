#!/usr/bin/env node
/**
 * Regenerates src/features/appIcons/appIconNames.ts from the dashboard-icons
 * collection (https://github.com/homarr-labs/dashboard-icons, Apache-2.0):
 * the names of all icons, so the app can match cards to icons offline and
 * request only the one icon it needs.
 *
 *   node scripts/update-app-icons.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source =
  'https://raw.githubusercontent.com/homarr-labs/dashboard-icons/main/metadata.json'

const response = await fetch(source)

if (!response.ok) {
  throw new Error(`${source}: HTTP ${response.status}`)
}

const metadata = await response.json()
const names = Object.entries(metadata)
  .filter(([name]) => /^[a-z0-9][a-z0-9-]*$/.test(name))
  // Icons without an SVG get a "*": they are loaded as PNG.
  .map(([name, entry]) => (entry.base === 'svg' ? name : `${name}*`))
  .sort()

writeFileSync(
  resolve(root, 'src/features/appIcons/appIconNames.ts'),
  `// Generated by scripts/update-app-icons.mjs from homarr-labs/dashboard-icons
// (Apache-2.0). Do not edit; run the script to update.
// ${names.length} icons; "*" marks icons that exist only as PNG.
export const APP_ICON_NAMES =
  '${names.join(' ')}'
`,
)

console.log(`${names.length} app icons`)
